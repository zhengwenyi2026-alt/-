const DICT = { 'zh-TW': TW, en: EN, ja: JA, ko: KO };

/** 把 {name} 占位替换成参数值 */
function interpolate(text, params) {
  if (!params) return text;
  return text.replace(/\{([a-zA-Z0-9_]+)\}/g, (whole, key) => {
    const value = params[key];
    return value === undefined || value === null ? whole : String(value);
  });
}

/** 取当前语言的译文；未命中则回显中文原文 */
function t(key, params, lang) {
  const source = String(key ?? '');
  const table = DICT[lang] || DICT[DEFAULT_LANG];
  const hit = table ? table[source] : undefined;
  return interpolate(hit || source, params);
}

/** 按系统 locale 选一个受支持的语言 */
function detect(locale) {
  const raw = String(locale || 'en').toLowerCase();
  if (raw.startsWith('zh')) {
    if (raw.includes('tw') || raw.includes('hant') || raw.includes('hk')) return 'zh-TW';
    return 'zh-CN';
  }
  for (const item of LANGS) if (raw.startsWith(item.code.toLowerCase())) return item.code;
  if (raw.startsWith('ja')) return 'ja';
  if (raw.startsWith('ko')) return 'ko';
  return 'en';
}

function isSupported(lang) {
  return LANGS.some((item) => item.code === lang);
}

return { LANGS, DEFAULT_LANG, t, detect, isSupported, interpolate };
